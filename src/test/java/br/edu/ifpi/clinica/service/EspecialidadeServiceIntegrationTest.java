package br.edu.ifpi.clinica.service;

import br.edu.ifpi.clinica.dto.request.EspecialidadeRequestDTO;
import br.edu.ifpi.clinica.exception.DadoInvalidoException;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.autoconfigure.jdbc.AutoConfigureTestDatabase;
import org.springframework.boot.test.autoconfigure.orm.jpa.DataJpaTest;
import org.springframework.context.annotation.Import;
import org.springframework.transaction.annotation.Propagation;
import org.springframework.transaction.annotation.Transactional;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;

import static org.junit.jupiter.api.Assertions.*;

// Integração real: EspecialidadeService -> EspecialidadeRepository (JPA) -> H2 em memória
@DataJpaTest(properties = {
        "spring.datasource.url=" + EspecialidadeServiceIntegrationTest.URL,
        "spring.datasource.driver-class-name=org.h2.Driver",
        "spring.datasource.username=sa",
        "spring.datasource.password=",
        "spring.jpa.hibernate.ddl-auto=none"
})
@AutoConfigureTestDatabase(replace = AutoConfigureTestDatabase.Replace.NONE)
@Transactional(propagation = Propagation.NOT_SUPPORTED)
@Import(EspecialidadeService.class)
class EspecialidadeServiceIntegrationTest {

    static final String URL = "jdbc:h2:mem:clinica;DB_CLOSE_DELAY=-1";

    @Autowired
    private EspecialidadeService especialidadeService;

    private Connection connection;

    @BeforeEach
    void setUp() throws SQLException {
        connection = DriverManager.getConnection(URL, "sa", "");
        try (Statement st = connection.createStatement()) {
            st.execute("""
                    CREATE TABLE especialidade (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        nome VARCHAR(255) NOT NULL UNIQUE,
                        valor_consulta DOUBLE PRECISION NOT NULL
                    )""");
            st.execute("INSERT INTO especialidade (nome, valor_consulta) VALUES ('Cardiologia', 250.0)");
        }
    }

    @AfterEach
    void tearDown() throws SQLException {
        try (Statement st = connection.createStatement()) {
            st.execute("DROP TABLE especialidade");
        }
        connection.close();
    }

    @Test
    void insertDevePersistirNovaEspecialidadeNoBanco() throws SQLException {
        especialidadeService.insert(new EspecialidadeRequestDTO("Dermatologia", 180.0));

        try (PreparedStatement ps = connection.prepareStatement(
                "SELECT valor_consulta FROM especialidade WHERE nome = ?")) {
            ps.setString(1, "Dermatologia");
            try (ResultSet rs = ps.executeQuery()) {
                assertTrue(rs.next());
                assertEquals(180.0, rs.getDouble("valor_consulta"));
            }
        }
        assertEquals(2, contarEspecialidades());
    }

    @Test
    void insertComNomeDuplicadoDeveLancarExcecaoESemAlterarBanco() throws SQLException {
        assertThrows(DadoInvalidoException.class,
                () -> especialidadeService.insert(new EspecialidadeRequestDTO("Cardiologia", 300.0)));

        assertEquals(1, contarEspecialidades());
        try (Statement st = connection.createStatement();
                ResultSet rs = st.executeQuery("SELECT valor_consulta FROM especialidade WHERE nome = 'Cardiologia'")) {
            assertTrue(rs.next());
            assertEquals(250.0, rs.getDouble("valor_consulta"));
        }
    }

    private int contarEspecialidades() throws SQLException {
        try (Statement st = connection.createStatement();
                ResultSet rs = st.executeQuery("SELECT COUNT(*) FROM especialidade")) {
            rs.next();
            return rs.getInt(1);
        }
    }
}
